#!/usr/bin/env python3
"""Local, dependency-free evidence index and reviewed memory lifecycle."""
import argparse
import datetime as dt
import hashlib
import json
import math
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
ALLOWED = {'research', 'drafts', 'data', 'analysis', 'methods', 'templates', 'memory', 'evaluation'}
EXTENSIONS = {'.md', '.txt', '.csv', '.json'}
INDEX = 'indexes/search.json'
CARDS = 'memory/cards.json'

def digest(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest()

def read_json(path, default=None):
    p = safe_file(path)
    return json.loads(p.read_text(encoding='utf-8')) if p.exists() else default

def write_json(path, value):
    p = safe_file(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

def safe_file(path):
    p = Path(path)
    if p.is_absolute() or '..' in p.parts or not p.parts:
        raise ValueError('Invalid repository-relative path')
    target = ROOT / p
    if target.is_symlink() or any(a.is_symlink() for a in target.parents if a != ROOT.parent):
        raise ValueError('Symlinks are not accepted')
    if not target.resolve().is_relative_to(ROOT.resolve()):
        raise ValueError('Path escapes repository')
    return target

def sources():
    out = {}
    for p in sorted(ROOT.rglob('*')):
        rel = p.relative_to(ROOT)
        if any(x.startswith('.') for x in rel.parts) or p.is_symlink() or not p.is_file():
            continue
        if len(rel.parts) > 1 and rel.parts[0] not in ALLOWED:
            continue
        if rel.as_posix() == CARDS or p.suffix not in EXTENSIONS or p.stat().st_size > 1_000_000:
            continue
        safe_file(rel.as_posix())
        try:
            out[rel.as_posix()] = p.read_text(encoding='utf-8')
        except UnicodeError:
            continue
    return out

def tokens(text):
    return re.findall(r'[^\W_]+', text.casefold(), re.UNICODE)

def build():
    docs = sources()
    chunks = []
    for path, text in docs.items():
        lines = text.splitlines()
        for start in range(0, len(lines), 24):
            part = '\n'.join(lines[start:start + 32])
            chunks.append({'path': path, 'start': start + 1, 'end': min(start + 32, len(lines)),
                           'text': part, 'tokens': tokens(path + ' ' + part)})
    index = {'version': 1, 'files': {p: digest(t) for p, t in docs.items()}, 'chunks': chunks}
    write_json(INDEX, index)
    table = ['# Full repository document index', '', 'Generated by `python tools/memory.py build`. Each link opens the source; hashes are in search.json.', '', '| File | Lines |', '|---|---:|']
    table += [f'| [{p}](../{p}) | {len(t.splitlines())} |' for p, t in docs.items()]
    table += ['', 'Code, hidden files, binary documents and files over 1 MB are not searched. See ../memory/PROTOCOL.md for extraction and exclusions.', '']
    safe_file('indexes/README.md').write_text('\n'.join(table), encoding='utf-8')
    return index

def evidence(path, start, end):
    docs = sources()
    if path not in docs:
        raise ValueError('Evidence must be an indexed source document')
    lines = docs[path].splitlines()
    if not 1 <= start <= end <= len(lines):
        raise ValueError('Invalid evidence line range')
    return {'path': path, 'start': start, 'end': end, 'sha256': digest(docs[path]),
            'excerpt': '\n'.join(lines[start - 1:end])}

def stale(card):
    for ev in card['evidence']:
        try:
            if digest(safe_file(ev['path']).read_text(encoding='utf-8')) != ev['sha256']:
                return True
        except (OSError, ValueError):
            return True
    return False

def expired(card):
    return bool(card.get('review_on') and card['review_on'] <= dt.date.today().isoformat())

def propose(args):
    cards = read_json(CARDS, [])
    if not re.fullmatch(r'[A-Za-z0-9_-]+', args.id) or any(c['id'] == args.id for c in cards):
        raise ValueError('ID must be unique and contain letters, digits, _ or -')
    if not args.claim.strip() or not args.scope.strip():
        raise ValueError('Claim and scope are required')
    if args.review_on:
        dt.date.fromisoformat(args.review_on)
    ev = evidence(args.source, args.start, args.end)
    cards.append({'id': args.id, 'kind': args.kind, 'claim': args.claim, 'scope': args.scope,
                  'status': 'candidate', 'evidence': [ev], 'created': dt.date.today().isoformat(),
                  'review_on': args.review_on, 'events': []})
    write_json(CARDS, cards)
    print('Candidate saved; not yet durable knowledge:', args.id)

def transition(args):
    cards = read_json(CARDS, [])
    card = next((c for c in cards if c['id'] == args.id), None)
    if card is None:
        raise ValueError('Unknown card')
    allowed = {'candidate': {'active', 'rejected'}, 'active': {'disputed', 'superseded', 'archived'},
               'disputed': {'active', 'superseded', 'archived'}}
    if args.status not in allowed.get(card['status'], set()):
        raise ValueError('Invalid lifecycle transition; preserve terminal history')
    if not args.reviewer.strip() or not args.reason.strip():
        raise ValueError('Named reviewer and substantive rationale required')
    if args.status == 'active' and (stale(card) or expired(card)):
        raise ValueError('Changed evidence or review date reached; create a freshly evidenced candidate')
    if args.status == 'superseded':
        replacement = next((c for c in cards if c['id'] == args.replacement), None)
        if not replacement or replacement['status'] != 'active' or replacement['id'] == card['id'] or stale(replacement) or expired(replacement):
            raise ValueError('Supersession requires a different, valid active replacement')
        card['replacement'] = args.replacement
    card['events'].append({'from': card['status'], 'to': args.status, 'reviewer': args.reviewer,
                           'reason': args.reason, 'at': dt.datetime.now(dt.timezone.utc).isoformat()})
    card['status'] = args.status
    write_json(CARDS, cards)
    print('Recorded transition:', args.id, args.status)

def search(args):
    index = read_json(INDEX)
    if index is None or index['files'] != {p: digest(t) for p, t in sources().items()}:
        index = build()
    query = set(tokens(args.query))
    chunks = index['chunks']
    avg = sum(len(c['tokens']) for c in chunks) / max(len(chunks), 1)
    frequencies = {term: sum(term in c['tokens'] for c in chunks) for term in query}
    scored = []
    for c in chunks:
        ts = c['tokens']
        score = 0
        for term in query:
            freq = ts.count(term)
            if not freq:
                continue
            df = frequencies[term]
            idf = math.log(1 + (len(chunks) - df + .5) / (df + .5))
            score += idf * freq * 2.2 / (freq + 1.2 * (.25 + .75 * len(ts) / max(avg, 1)))
        if score:
            scored.append((score, c))
    selected = []
    used = 0
    for score, c in sorted(scored, key=lambda x: (-x[0], x[1]['path'], x[1]['start'])):
        if any(p['path'] == c['path'] and max(p['start'], c['start']) <= min(p['end'], c['end']) for p in selected):
            continue
        size = len(c['text'])
        if used + size > args.budget:
            continue
        selected.append({k: v for k, v in c.items() if k != 'tokens'})
        used += size
        if len(selected) >= args.limit:
            break
    print(json.dumps({'query': args.query, 'evidence': selected, 'characters': used,
                      'note': 'Lexical candidates, not verified answers. Open cited sources; absence is not proof.'}, ensure_ascii=False, indent=2))

def cycle():
    cards = read_json(CARDS, [])
    groups = {'usable': [], 'review_due': [], 'candidate': [], 'disputed': [], 'history': []}
    for c in cards:
        if c['status'] == 'active':
            groups['review_due' if stale(c) or expired(c) else 'usable'].append(c['id'])
        elif c['status'] in {'candidate', 'disputed'}:
            groups[c['status']].append(c['id'])
        else:
            groups['history'].append(c['id'])
    usable = [c for c in cards if c['id'] in groups['usable']]
    write_json('indexes/memory.json', {'groups': groups, 'usable': usable})
    lines = ['# Memory index', '', 'Generated by `python tools/memory.py cycle`. Only usable cards are eligible as durable context; read their evidence.', '']
    for group, ids in groups.items():
        lines += [f'## {group}', ', '.join(ids) or '(empty)', '']
    lines += ['## Usable claims', '']
    for c in usable:
        lines += [f"### {c['id']}: {c['kind']}", c['claim'], 'Scope: ' + c['scope']]
        for e in c['evidence']:
            lines.append(f"Evidence: [{e['path']}](../{e['path']}) lines {e['start']}-{e['end']}")
        lines.append('')
    safe_file('indexes/MEMORY.md').write_text('\n'.join(lines), encoding='utf-8')
    print(json.dumps(groups, ensure_ascii=False))

def main():
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest='command', required=True)
    sub.add_parser('build')
    sub.add_parser('cycle')
    s = sub.add_parser('search')
    s.add_argument('query'); s.add_argument('--limit', type=int, default=6); s.add_argument('--budget', type=int, default=12000)
    c = sub.add_parser('propose')
    for flag in ('id', 'claim', 'scope', 'source'):
        c.add_argument('--' + flag, required=True)
    c.add_argument('--start', type=int, required=True); c.add_argument('--end', type=int, required=True)
    c.add_argument('--kind', choices=['decision', 'fact', 'method', 'correction'], required=True)
    c.add_argument('--review-on')
    t = sub.add_parser('transition')
    for flag in ('id', 'status', 'reviewer', 'reason'):
        t.add_argument('--' + flag, required=True)
    t.add_argument('--replacement')
    args = p.parse_args()
    try:
        if args.command == 'build':
            print('Indexed', len(build()['files']), 'documents')
        elif args.command == 'search':
            if args.limit < 1 or args.budget < 1:
                raise ValueError('Positive limit and budget required')
            search(args)
        elif args.command == 'propose':
            propose(args)
        elif args.command == 'transition':
            transition(args)
        else:
            build(); cycle()
    except (ValueError, OSError, KeyError) as e:
        p.exit(2, str(e) + '\n')

if __name__ == '__main__':
    main()
